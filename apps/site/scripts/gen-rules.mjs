// Per-rule sitemap entries. The 61 /docs/rules/<id> pages are real
// content and worth indexing individually. The YAML rule library is
// the single source of truth: future rule additions auto-emit
// sitemap entries on the next `pnpm gen:rules` run.
//
// Idempotent: strips and replaces the auto-generated block between
// the BEGIN / END markers so the static entries above stay intact.
//
// lastmod per rule comes from `git log -1 --format=%cs <yaml-file>`
// (the last commit date for that specific YAML; falls back to file
// mtime if git is unavailable e.g. shallow CI checkout).
function writeSitemap(rules) {
  if (!fs.existsSync(SITEMAP_OUT)) {
    console.warn(`[gen-rules] ${path.relative(SITE_ROOT, SITEMAP_OUT)} not found; skipping per-rule sitemap entries`);
    return;
  }

  const entries = rules.map((rule) => {
    let lastmod;
    try {
      lastmod = execFileSync(
        "git",
        ["log", "-1", "--format=%cs", "--", rule._yamlPath],
        { encoding: "utf8", stdio: ["pipe", "pipe", "ignore"] },
      ).trim();
    } catch {
      lastmod = "";
    }
    if (!lastmod) {
      // Fallback to file mtime in YYYY-MM-DD form.
      const mt = fs.statSync(rule._yamlPath).mtime;
      lastmod = mt.toISOString().slice(0, 10);
    }
    return [
      "  <url>",
      `    <loc>https://glassmkr.com/docs/rules/${rule.id}</loc>`,
      `    <lastmod>${lastmod}</lastmod>`,
      "    <changefreq>weekly</changefreq>",
      "    <priority>0.6</priority>",
      "  </url>",
    ].join("\n");
  }).join("\n");

  const block = `  ${SITEMAP_BEGIN}\n${entries}\n  ${SITEMAP_END}`;

  let sitemap = fs.readFileSync(SITEMAP_OUT, "utf8");
  const beginIdx = sitemap.indexOf(SITEMAP_BEGIN);
  const endIdx = sitemap.indexOf(SITEMAP_END);

  if (beginIdx >= 0 && endIdx >= 0 && endIdx > beginIdx) {
    // Replace existing block: find the indented BEGIN line through the
    // indented END line + trailing newline.
    const lineStart = sitemap.lastIndexOf("\n", beginIdx) + 1;
    const lineEnd = sitemap.indexOf("\n", endIdx + SITEMAP_END.length);
    const before = sitemap.slice(0, lineStart);
    const after = sitemap.slice(lineEnd + 1);
    sitemap = before + block + "\n" + after;
  } else {
    // First-time insert: place the block just before </urlset>.
    sitemap = sitemap.replace("</urlset>\n", block + "\n</urlset>\n");
  }

  // Rebuild the whole file: the static half used to be hand-kept, which is how
  // three live pages went missing from it and the homepage kept a May lastmod
  // through an August rewrite.
  const rebuilt = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    writeStaticSitemapEntries(),
    `  ${SITEMAP_BEGIN}`,
    entries,
    `  ${SITEMAP_END}`,
    "</urlset>",
    "",
  ].join("\n");
  fs.writeFileSync(SITEMAP_OUT, rebuilt);
  console.log(`[gen-rules] wrote ${rules.length} per-rule entries to ${path.relative(SITE_ROOT, SITEMAP_OUT)}`);
}

