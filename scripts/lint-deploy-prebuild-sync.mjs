#!/usr/bin/env node
//
// CI lint rule: every file that the prebuild step writes via fs.writeFileSync
// must be either (a) listed in scripts/deploy.sh's "clear generated artifacts"
// checkout block before `git pull --ff-only`, OR (b) ignored via .gitignore.
//
// Why this exists
// ---------------
// 2026-05-22: four consecutive prod deploys failed in a row (PRs #223 / #224
// / #225 / #226) because task #164 added `apps/site/static/sitemap.xml` as
// a new fs.writeFileSync target in apps/site/scripts/gen-rules.mjs but the
// deploy guard in scripts/deploy.sh was only carrying the three previous
// outputs (rules.json + llms-full.txt + llms.txt). After the first
// successful prebuild on the prod server, sitemap.xml went dirty in the
// working tree and every subsequent `git pull --ff-only` failed with:
//
//   error: Your local changes to the following files would be overwritten
//   by merge: apps/site/static/sitemap.xml
//
// Prod was effectively pinned at a pre-Codex-F3 state for ~4 hours.
//
// The fix on the deploy.sh side is one line per new prebuild output. This
// lint makes the missing-line mistake impossible to ship: any prebuild
// fs.writeFileSync target that isn't covered by deploy.sh OR .gitignore
// fails CI before the PR can merge.
//
// What it checks
// --------------
// 1. Parses `apps/site/scripts/gen-rules.mjs` (the only prebuild script
//    in the monorepo at time of writing) for output path constants of
//    the form:
//      const NAME_OUT = path.resolve(SITE_ROOT, "<relpath>");
//    and matching `fs.writeFileSync(NAME_OUT, ...)` calls. The intersection
//    gives the set of "prebuild outputs."
//
// 2. Parses `scripts/deploy.sh` for the multi-line `git checkout -- ...`
//    block immediately preceding the fast-forward pull, and extracts the
//    list of paths inside it.
//
// 3. Parses `.gitignore` patterns. A prebuild output is considered
//    "covered" if a .gitignore line literally matches its path (full
//    glob semantics is overkill here; we keep it simple).
//
// 4. For each prebuild output: if NOT covered by deploy.sh AND NOT covered
//    by .gitignore, fail with a clear message naming the file and the two
//    options to fix.
//
// Exit code 0 on success, 1 on lint failure. Designed to be cheap (single
// pass over three files), runs in <100ms.
//
// Scope is intentionally narrow: only apps/site/scripts/gen-rules.mjs.
// If a future app grows its own prebuild script with fs.writeFileSync
// outputs, add it to PREBUILD_SCRIPTS below.

import { readFileSync } from "node:fs";
import { resolve, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = resolve(fileURLToPath(import.meta.url), "..", "..");

/**
 * Prebuild scripts that emit committed files via fs.writeFileSync.
 * Each entry is the script path (repo-relative) + the base directory
 * the path.resolve(BASE, ...) calls anchor against.
 */
const PREBUILD_SCRIPTS = [
  {
    script: "apps/site/scripts/gen-rules.mjs",
    baseConst: "SITE_ROOT",
    base: "apps/site",
  },
];

/**
 * Extract prebuild output paths from a script. Looks for constants
 * declared as `const NAME = path.resolve(BASE_CONST, "<relpath>")` AND
 * referenced by `fs.writeFileSync(NAME, ...)`. Both halves must match;
 * a `path.resolve` not used in a writeFileSync is not an output, and a
 * writeFileSync with a non-resolve target isn't tracked (defensive).
 */
function extractWriteTargets(scriptPath, baseConst, base) {
  const text = readFileSync(resolve(REPO_ROOT, scriptPath), "utf8");

  // const FOO_OUT = path.resolve(SITE_ROOT, "static/sitemap.xml");
  const constRe = new RegExp(
    `^const\\s+(\\w+)\\s*=\\s*path\\.resolve\\(\\s*${baseConst}\\s*,\\s*"([^"]+)"\\s*\\)`,
    "gm",
  );
  const constMap = new Map();
  for (const m of text.matchAll(constRe)) {
    constMap.set(m[1], m[2]);
  }

  // fs.writeFileSync(FOO_OUT, ...)
  const writeRe = /fs\.writeFileSync\s*\(\s*(\w+)\s*,/g;
  const used = new Set();
  for (const m of text.matchAll(writeRe)) {
    if (constMap.has(m[1])) used.add(m[1]);
  }

  const outputs = [];
  for (const constName of used) {
    const rel = constMap.get(constName);
    outputs.push({
      constName,
      repoRelative: `${base}/${rel}`,
    });
  }
  return outputs;
}

/**
 * Read scripts/deploy.sh and pull the file list out of the
 * `git checkout -- \\\n  path1 \\\n  path2 ...` block immediately
 * before the fast-forward pull. We anchor on the marker comment so
 * other `git checkout` calls in the script (if any are added later)
 * don't accidentally satisfy the lint.
 */
function extractDeployCheckoutList() {
  const text = readFileSync(resolve(REPO_ROOT, "scripts/deploy.sh"), "utf8");
  const marker = /Clearing generated artifacts \(regenerated by prebuild\)\.\.\."[\s\S]*?git checkout -- \\([\s\S]*?)\s*2>\/dev\/null/;
  const m = text.match(marker);
  if (!m) {
    throw new Error(
      "[lint:deploy-prebuild-sync] could not locate the deploy.sh " +
        "'Clearing generated artifacts' block. Has the marker comment " +
        "or the `git checkout --` invocation changed? Update this lint.",
    );
  }
  const block = m[1];
  // Each path is on its own continuation line, possibly with trailing
  // backslash. Trim whitespace + drop empty + drop trailing backslash.
  const paths = block
    .split("\n")
    .map((line) => line.replace(/\\$/, "").trim())
    .filter((line) => line.length > 0);
  return new Set(paths);
}

function extractGitignorePatterns() {
  try {
    const text = readFileSync(resolve(REPO_ROOT, ".gitignore"), "utf8");
    return new Set(
      text
        .split("\n")
        .map((l) => l.trim())
        .filter((l) => l.length > 0 && !l.startsWith("#")),
    );
  } catch {
    return new Set();
  }
}

let failures = 0;
function fail(msg) {
  console.error(msg);
  failures++;
}

const deployCovered = extractDeployCheckoutList();
const gitignore = extractGitignorePatterns();

for (const { script, baseConst, base } of PREBUILD_SCRIPTS) {
  const outputs = extractWriteTargets(script, baseConst, base);
  if (outputs.length === 0) {
    fail(
      `[lint:deploy-prebuild-sync] WARNING: no writeFileSync outputs found in ${script}. ` +
        `Has the parser pattern drifted? Check the const-name + writeFileSync convention.`,
    );
    continue;
  }
  for (const out of outputs) {
    const inDeploy = deployCovered.has(out.repoRelative);
    const inGitignore = gitignore.has(out.repoRelative);
    if (!inDeploy && !inGitignore) {
      fail(
        `[lint:deploy-prebuild-sync] FAIL: ${out.repoRelative} ` +
          `(from ${script} -> const ${out.constName})\n` +
          `  This prebuild output is neither in scripts/deploy.sh's ` +
          `'Clearing generated artifacts' checkout list nor in .gitignore.\n` +
          `  After the first successful prebuild on a deploy target, this ` +
          `file goes dirty and every subsequent 'git pull --ff-only' will ` +
          `fail until manual recovery. This is exactly how prod got stuck ` +
          `on 2026-05-22 across four PR deploys.\n` +
          `  Fix: add '${out.repoRelative}' to the deploy.sh checkout-clean ` +
          `block, OR (if the file shouldn't be committed at all) move it ` +
          `to .gitignore and delete the tracked copy.`,
      );
    }
  }
}

if (failures > 0) {
  console.error(`\n${failures} lint failure(s).`);
  process.exit(1);
}
console.log("[lint:deploy-prebuild-sync] OK; every prebuild output is covered.");
