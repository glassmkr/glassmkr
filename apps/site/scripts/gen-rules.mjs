async function fetchLatestCrucible() {
  try {
    const res = await fetch(NPM_DIST_TAGS_URL, {
      headers: {
        "user-agent": "glassmkr-site-gen",
        accept: "application/json",
      },
      signal: AbortSignal.timeout(5000),
    });
    if (!res.ok) throw new Error(`npm ${res.status}`);
    const body = await res.json();
    const tag = (body.latest ?? "").replace(/^v/, "");
    if (!/^\d+\.\d+\.\d+$/.test(tag)) throw new Error(`unparseable ${tag}`);
    return tag;
  } catch (err) {
    console.warn(
      `[gen-rules] npm fetch failed; using FALLBACK_CRUCIBLE_VERSION ${FALLBACK_CRUCIBLE_VERSION}: ${err?.message ?? err}`,
    );
    return FALLBACK_CRUCIBLE_VERSION;
  }
}

// Category map + display order live in a shared data module so the CI guard
// (scripts/lint-rule-category.mjs) can import the SAME object instead of
// regex-parsing this file. See rule-categories.mjs for why.
import { CATEGORY, CATEGORY_ORDER } from "./rule-categories.mjs";

// Load every *.yaml under the rules dir, but project to the public
// catalog shape only. The FIX block (prerequisites/safe_mode/variants/
// validation/rollback/impact/provenance) is dashboard-internal and is
// dropped here, before anything downstream sees it.
function loadRules() {
  const files = fs
    .readdirSync(RULES_DIR)
    .filter((f) => f.endsWith(".yaml"))
    .sort();
  const unknown = [];
  const rules = files.map((f) => {
    const filePath = path.join(RULES_DIR, f);
    const raw = fs.readFileSync(filePath, "utf8");
    const parsed = parseYaml(raw);
    if (!parsed || typeof parsed !== "object" || !parsed.id) {
      throw new Error(`[gen-rules] ${f}: missing or invalid id`);
    }
    const category = CATEGORY[parsed.id];
    if (!category) unknown.push(parsed.id);
    return {
      id: parsed.id,
      priority: parsed.priority,
      title: parsed.title,
      summary: parsed.summary,
      _category: category || "Other",
      _yamlPath: filePath,
    };
  });
  if (unknown.length > 0) {
    // Hard-fail: an unmapped rule falls to _category "Other", which is not
    // in CATEGORY_ORDER, so it is silently dropped from the llms-full.txt
    // catalog body and the /docs/rules grouping. That drift shipped once
    // (4 rules missing, corpus said 65 in the header but listed 61) and is
    // exactly the kind of count mismatch an agent trips over. Fail the
    // build so a new rule cannot merge without being categorised.
    throw new Error(
      `[gen-rules] ${unknown.length} rule(s) without a CATEGORY entry:\n  - ${unknown.join("\n  - ")}\n  Add each to the CATEGORY map in apps/site/scripts/gen-rules.mjs.`,
    );
  }
  return rules;
}

function writeJson(rules) {
  fs.mkdirSync(path.dirname(DATA_OUT), { recursive: true });
  const sorted = [...rules].sort((a, b) => {
    const ca = CATEGORY_ORDER.indexOf(a._category);
    const cb = CATEGORY_ORDER.indexOf(b._category);
    if (ca !== cb) return ca - cb;
    return a.id.localeCompare(b.id);
  });
  // _yamlPath stays in memory only (sitemap lastmod above needs it); the
  // emitted JSON must not carry build-machine absolute paths: rules.json is
  // committed and imported by client components, so the field would leak
  // local filesystem layout into both the repo and the shipped bundle.
  const emitted = sorted.map(({ _yamlPath, ...rest }) => rest);
  fs.writeFileSync(DATA_OUT, JSON.stringify(emitted, null, 2));
  console.log(`[gen-rules] wrote ${sorted.length} rules to ${path.relative(SITE_ROOT, DATA_OUT)}`);
}

