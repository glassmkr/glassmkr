// Build-time generator for the public rule catalog + the LLM-friendly
// corpus file. Originally per CONTENT_TRANCHE_3_DOCS_TRUST_FURNACE_2026-05-17.md;
// 2026-05-20 the FIX-workflow content was stripped from public output:
// the per-distro variants + safe_mode + validation + rollback + impact
// + provenance are dashboard-internal (the moat) and must not be
// rendered as public docs or shipped in the LLM corpus.
//
// Reads the YAML rule library at apps/dashboard/src/lib/server/alerts/
// rules/ and emits three derived artefacts inside the site app:
//
//   apps/site/src/lib/data/rules.json
//     Compact JSON of `{id, priority, title, summary, _category}`
//     only; no FIX content. Imported by /docs/rules and
//     /docs/rules/[id] page loaders so every request renders the
//     stripped public catalog.
//
//   apps/site/static/llms-full.txt
//     Plain-text catalog with the same redacted shape. The /llms.txt
//     index points here as the single-file corpus for AI agents.
//
//   apps/site/static/llms.txt
//     LLM-first index. Includes the current Crucible version pulled
//     from npm registry at build time, with a hardcoded fallback if
//     npm is unreachable.
//
// Runs via `pnpm gen:rules` or automatically before `pnpm build` via
// the `prebuild` hook. Outputs are gitignored to keep one source of
// truth; SSR build always regenerates.

