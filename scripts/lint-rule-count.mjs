#!/usr/bin/env node
//
// Guard: every advertised alert-rule count on the site must equal the real count.
//
// Why this gate exists: the marketing and docs copy hardcodes "N alert rules" in
// dozens of places, and it has gone stale on every single rule addition. This is
// the FOURTH reconcile: 62 -> 65 (#505), 65 -> 68 (#554), 68 -> 70 (this one), with
// stragglers surviving each pass (a "62" was still live on /docs/rules, the page
// that lists the rules, and a "65" on /about and /docs/faq). Reconciling by hand
// and hoping is demonstrably not enough.
//
// Canonical count: the length of apps/site/src/lib/data/rules.json, which is
// generated from the rule YAMLs by gen-rules.mjs and is git-tracked, so this gate
// needs no build step. That file is the same source the /docs rule tables render
// from, so the number here cannot disagree with the tables.
//
// WHY NOT DERIVE THE COPY INSTEAD, which would remove the need for this gate: the
// 83 claim sites span three syntactic contexts (Svelte markup, HTML attributes, and
// quoted strings inside JSON.stringify for JSON-LD). The last group needs its quote
// type changed to interpolate, and a mechanical transform through structured data on
// customer-facing pages is the risky part of that change. A guard reaches the same
// end state (drift cannot merge) without touching the rendering. Deriving remains
// the better long-term answer for the pure-prose cases and is worth revisiting; if
// you do it, this gate still earns its keep on whatever stays hardcoded.
//
// Requiring a copy edit per rule addition is a mild feature, not only a cost: a
// count change is a reasonable moment to re-read the surrounding sentence, because
// neighbouring claims ("9 categories") can go stale in the same release.
//
// DATED SURFACES ARE EXCLUDED ON PURPOSE. A blog post or changelog entry stated a
// number that was true when published; rewriting it would falsify the archive. The
// exclusion is an explicit list below rather than an accident of the regex, so the
// decision is visible and reviewable.

import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const here = fileURLToPath(new URL(".", import.meta.url));
const repoRoot = join(here, "..");

export const RULES_JSON = "apps/site/src/lib/data/rules.json";
export const SCAN_ROOT = "apps/site/src";

// Dated content: accurate at publication, deliberately never reconciled.
export const DATED_PATH_PATTERNS = [/\/blog\//, /\/docs\/changelog\//];

/**
 * Matches an advertised count: a 2-digit number, then up to two intervening words,
 * then a rule-ish noun.
 *
 * The intervening-words allowance is load-bearing and both regexes written during
 * this task got it wrong at first. "68 built-in rules" and "62 Glassmkr alert rules"
 * are real claims that a tighter pattern silently skipped, and the second one
 * requires allowing a CAPITALIZED word. A guard that matches nothing reports OK, so
 * being too strict here is the dangerous direction.
 */
const CLAIM = /\b(\d{2})\b([ -](?:[A-Za-z][A-Za-z-]* ){0,2}(?:rules?|alerts?|opinionated)\b)/g;

// Durations read like counts ("60 minutes of stale alerting") and must never match.
const TIME_WORDS = /minute|second|hour|day|week|month/i;

/** Pure: is this path dated content that must keep its original number? */
export function isDated(path) {
  return DATED_PATH_PATTERNS.some((re) => re.test(path));
}

/** Pure: extract claims from one file's source. Returns [{num, text}]. */
export function findClaims(src) {
  return [...src.matchAll(CLAIM)]
    .filter((m) => !TIME_WORDS.test(m[0]))
    .map((m) => ({ num: Number(m[1]), text: m[0] }));
}

/** Pure: given [{file, claims}], flag every claim whose number is not `expected`. */
export function checkClaims(entries, expected) {
  const violations = [];
  for (const { file, claims } of entries) {
    for (const c of claims) {
      if (c.num !== expected) {
        violations.push(`${file}: advertises "${c.text}" but the real count is ${expected}`);
      }
    }
  }
  return violations;
}

const isMain = import.meta.url === `file://${process.argv[1]}`;
if (isMain) {
  let expected;
  try {
    const rules = JSON.parse(readFileSync(join(repoRoot, RULES_JSON), "utf8"));
    if (!Array.isArray(rules) || rules.length === 0) throw new Error("not a non-empty array");
    expected = rules.length;
  } catch (err) {
    console.error(
      `[lint:rule-count] cannot read the canonical count from ${RULES_JSON}: ${err.message}. ` +
        `That file is generated by gen-rules.mjs and git-tracked; do not delete it.`,
    );
    process.exit(1);
  }

  const entries = [];
  let datedSkipped = 0;
  const walk = (rel) => {
    let items;
    try {
      items = readdirSync(join(repoRoot, rel), { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of items) {
      const child = `${rel}/${e.name}`;
      if (e.isDirectory()) {
        if (e.name === "node_modules" || e.name === ".svelte-kit") continue;
        walk(child);
      } else if (e.name.endsWith(".svelte")) {
        if (isDated(child)) {
          datedSkipped++;
          continue;
        }
        const claims = findClaims(readFileSync(join(repoRoot, child), "utf8"));
        if (claims.length) entries.push({ file: child, claims });
      }
    }
  };
  walk(SCAN_ROOT);

  const found = entries.reduce((n, e) => n + e.claims.length, 0);

  // A guard that matches nothing passes silently, which is how the sibling
  // rule-category gate went green while the real generator failed. So a zero
  // count must never be accepted on trust.
  //
  // It used to be treated as proof that the regex had broken, on the reasoning
  // that the site advertises the count in dozens of places. That reasoning
  // expired: every remaining claim now renders from `{rules.length}`, which is
  // the end state check-ground-truth's `rulecount` check exists to force, and
  // the two gates were left contradicting each other. This one failed the build
  // for reaching the state the other one demands.
  //
  // The two causes are told apart by TESTING the matcher rather than inferring
  // its health from a count. If it still finds the claims in its own fixture,
  // it works, and zero claims in the source means the copy is fully derived.
  // Three matches, not four: CLAIM requires two digits, so "9 rules" is
  // deliberately outside it and is here as the negative case.
  const MATCHER_FIXTURE = "68 built-in rules, 62 Glassmkr alert rules, 70 opinionated rules, 9 rules";
  const fixtureClaims = findClaims(MATCHER_FIXTURE);
  if (fixtureClaims.length !== 3) {
    console.error(
      `[lint:rule-count] the matcher failed its own fixture: expected 3 claims in ` +
        `"${MATCHER_FIXTURE}", found ${fixtureClaims.length}. The regex is broken, ` +
        `so a clean run below would mean nothing. Fix the matcher.`,
    );
    process.exit(1);
  }
  if (found === 0) {
    console.log(
      `[lint:rule-count] OK: no hardcoded rule-count literal remains under ${SCAN_ROOT}. ` +
        `Every claim renders from rules.json, which is the state check-ground-truth ` +
        `requires. The matcher was verified against its fixture, so this is an empty ` +
        `result and not a broken regex.`,
    );
    process.exit(0);
  }

  const violations = checkClaims(entries, expected);

  if (violations.length > 0) {
    console.error("[lint:rule-count] violations:");
    for (const v of violations) console.error("  " + v);
    console.error(
      `\nThe canonical count is ${expected}, from ${RULES_JSON} (generated from the ` +
        `rule YAMLs). Update the copy to match. Check the sentence around each number ` +
        `too: neighbouring claims such as the category count can go stale in the same ` +
        `release. Dated blog and changelog pages are excluded on purpose and must keep ` +
        `their original numbers.`,
    );
    process.exit(1);
  }

  console.log(
    `[lint:rule-count] OK; ${found} advertised count(s) across ${entries.length} file(s) ` +
      `all read ${expected}; ${datedSkipped} dated page(s) skipped.`,
  );
}
